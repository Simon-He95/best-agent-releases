const pty = require('node-pty');
const { Terminal } = require('@xterm/headless');
const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'ime-probe-'));
const provider = path.join(home, 'provider.json');
fs.writeFileSync(provider, JSON.stringify({kind:'openai', model:'local-test', apiKey:'fixture', baseURL:'http://127.0.0.1:1/v1', compatibilityMode:'compatible'}));
const env = Object.fromEntries(Object.entries(process.env).filter(([k]) => !/^(NODE_|DIMCODE_|BEST_AGENT_|VITEST$)/i.test(k)));
Object.assign(env, { HOME:home, USERPROFILE:home, DIMCODE_HOME:home, DIMCODE_LANG:'en', BEST_AGENT_STORAGE_ROOT:path.join(home,'storage'), BEST_AGENT_PROVIDER_CONFIG:provider, VUE_TUI_TERMINAL_GRAPHICS:'none', TERM:'xterm-256color' });
const binary = path.resolve('release/best-agent-0.0.18-beta.1-win32-x64/bin/best-agent.exe');
const term = new Terminal({cols:120,rows:30,scrollback:0,allowProposedApi:true});
const child = pty.spawn(binary, ['chat'], { name:'xterm-256color', cols:120, rows:30, cwd:home, env, useConpty:true, useConptyDll:true, conptyInheritCursor:false });
term.onData(data => child.write(data));
child.onData(data => term.write(data));
const text = () => Array.from({length:term.rows}, (_,row) => term.buffer.active.getLine(term.buffer.active.baseY+row)?.translateToString(true) || '').join('\n');
const wait = ms => new Promise(resolve => setTimeout(resolve,ms));
(async () => {
  for (let n=0;n<400 && !text().includes('Type a message');n++) await wait(100);
  if (!text().includes('Type a message')) throw new Error('Home did not appear: '+text());
  child.write('abc');
  for (let n=0;n<100 && !text().includes('abc');n++) await wait(100);
  if (!text().includes('abc')) throw new Error('ASCII missing: '+text());
  child.write('你好');
  for (let n=0;n<100 && !text().includes('abc你好');n++) await wait(100);
  if (!text().includes('abc你好')) throw new Error('Committed CJK missing: '+text());
  console.log('PASS: released Windows x64 executable displays exact ASCII and precommitted Chinese through ConPTY');
  console.log('LIMITATION: injected text is already committed; no Windows Terminal GUI, IME candidate window, or physical keystrokes are exercised.');
  child.kill();
  process.exit(0);
})().catch(error => { console.error(error); child.kill(); process.exit(1); });
